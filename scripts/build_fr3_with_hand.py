"""将下载的 FR3 和夹爪组合为场景，保留上游模型原文件。"""
# 标准库处理路径和 XML；MuJoCo 负责模型挂接与编译。
from pathlib import Path
import xml.etree.ElementTree as ET

import mujoco


def main():
    # 读取两个上游模型，并以机器人末端 attachment_site 作为安装点。
    root = Path(__file__).resolve().parents[1]
    arm = mujoco.MjSpec.from_file(str(root / "models/robots/franka_fr3/scene.xml"))
    hand = mujoco.MjSpec.from_file(str(root / "models/robots/franka_hand/hand.xml"))
    # 本地安装约定：绕 FR3 法兰 Z 轴旋转 -45 度。
    hand.body("hand").quat = [0.9238795325, 0, 0, -0.3826834324]
    arm.attach(hand, prefix="gripper_", site=arm.site("attachment_site"))
    arm.compile()
    xml = ET.fromstring(arm.to_xml())
    # 导出的网格路径改为相对路径，使项目移动后仍然可以加载。
    xml.find("compiler").set("meshdir", ".")
    for mesh in xml.findall("asset/mesh"):
        folder = "franka_hand" if mesh.get("name", "").startswith("gripper_") else "franka_fr3"
        mesh.set("file", f"../robots/{folder}/assets/{Path(mesh.get('file')).name}")
    ET.indent(xml)
    target = root / "models/scenes/fr3_with_hand.xml"
    # 保存组合结果并重新加载，确认生成的 XML 和资源引用完整。
    target.write_text(
        '<!-- Generated by scripts/build_fr3_with_hand.py; upstream assets: Apache-2.0. -->\n'
        + ET.tostring(xml, encoding="unicode") + "\n", encoding="utf-8"
    )
    mujoco.MjModel.from_xml_path(str(target))
    print(target)


if __name__ == "__main__":
    main()
